"""Builds AI-assistant-friendly artefacts in dist/ (not committed):
  1. waste-tyre-pyrolysis-simulator_bundle.md   every source file in one text file, with a briefing header
  2. waste-tyre-pyrolysis-simulator.html        the dashboard as one self-contained HTML file
Run from the repo root:  python -m tools.bundle
"""
from pathlib import Path
from models.tea_financials import evaluate_plant_economics

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
SKIP_DIRS = {"dist", "__pycache__", ".git"}
SKIP_FILES = {"web/baseline_10tpd_nairobi.json",   # byte-identical copy of data/baseline_10tpd_nairobi.json
              "tools/bundle.py"}                    # its source contains the bundle tag syntax
LANG = {".py": "python", ".js": "javascript", ".html": "html", ".css": "css", ".json": "json",
        ".md": "markdown", ".yml": "yaml"}

HEADER = """# WASTE TYRE PYROLYSIS SIMULATOR: FULL SOURCE BUNDLE (written for AI assistants)

This single file contains the complete repository. Each file is wrapped in <file path="..."> ... </file>;
the path is the real repo path. Nothing else is needed to understand, run or modify the project.

## What the project is
A 10-TPD (tonnes per day) end-of-life-tyre pyrolysis plant model for Nairobi, Kenya: mass balance, energy
balance, syngas self-sufficiency, scrubber stoichiometry and a 5-year discounted cash flow (USD).
- models/            Python 3.9+ standard library only. Source of truth for all numbers.
- tests/             unittest suite.
- data/              baseline_10tpd_nairobi.json, generated by models/export_lookup.py (9 scenarios, 420-580 C).
- web/               static dashboard (index.html, style.css, app.js). No build step. Chart.js 4.4.1 from a CDN.
                     app.js re-implements the Python equations and checks itself against the baseline JSON on load.
- .github/workflows/ CI: run tests, fail if the baseline JSON is stale, deploy web/ to GitHub Pages.
- tools/bundle.py    generates this bundle and a single-file HTML build (omitted below).

## Commands
python -m unittest discover -s tests      run tests
python -m models.tea_financials           print baseline KPIs as JSON
python -m models.export_lookup            regenerate data/ and web/ baseline JSON (do this after any model change)
python -m http.server -d web 8000         serve the dashboard
python -m tools.bundle                    rebuild dist/

## Baseline (10 TPD, 500 C, 300 d/yr) as computed by the code
@@KPI@@

## Intentional deviations from the original design manual
- rCB is 2.67 t/d (26.7%), not 2.66; EQ 1 closes to 100% only at 26.7%.
- Self-sufficiency is 375.2% from the stated equations, not 378.3% (that would need a water latent heat of ~1,400 MJ/t).
- Payback and NPV use after-tax cash flow (net profit + depreciation), not net profit alone.
- Condenser cooling water is computed from assumed vapour heat capacities (about 178 m3/d), not the manual's 36.8 m3/d.
- GitHub Pages cannot publish from /web, so deployment uses the Actions workflow.
- Alarm thresholds are tiered: pressure 2.8 / 3.0 / 3.5 kPa, O2 0.85 / 1.0 vol%.

## Invariants to preserve
- The constants object K and the formulas in web/app.js must mirror models/mass_energy_balance.py and
  models/tea_financials.py. If you change one side, change the other, rerun export_lookup, and run the tests.
- Yield equations are valid only for 400 <= T <= 600 C; the Python raises ValueError outside that window.
- Mass must close: steel + TPO + syngas + rCB = feed. Moisture is carried inside the by-difference rCB remainder.
- Python uses the standard library only; the web app has no build step.

## Open items (not yet done)
- CO2e factor (0.85 t per t of tyres) is an unsourced placeholder.
- NEMA stack limits are not encoded; only H2S, NaOH and SO2 mass flows are computed.
- The PFD is a row of buttons with live values, not a drawn schematic.
- Condenser heat capacities and the 10 K cooling-water rise are assumptions.
- Economics are best-case (payback under 6 months); a conservative scenario with ramp-up is not built yet.
- The dashboard has not been tested in a browser.

## If asked to change code
Return each changed file in full, headed by its repo path, so it can be pasted over the original.
State which other files must change to stay consistent (see Invariants).
"""


def collect():
    files = []
    for p in sorted(ROOT.rglob("*")):
        rel = p.relative_to(ROOT).as_posix()
        if (not p.is_file() or set(p.relative_to(ROOT).parts) & SKIP_DIRS or rel in SKIP_FILES
                or p.suffix in {".zip", ".pyc"} or p.stat().st_size == 0):
            continue
        files.append((rel, p.read_text(encoding="utf-8")))
    return files


def build_bundle():
    e = evaluate_plant_economics()
    kpi = "\n".join(f"- {k}: {v}" for k, v in [
        ("TPO / rCB / steel / syngas (t/d)", f"{e['tpo_tpd']} / {e['rcb_tpd']} / {e['steel_tpd']} / {e['syngas_tpd']}"),
        ("Kiln burner duty (GJ/d)", e["reactor_duty_gj_day"]), ("Syngas energy (GJ/d)", e["syngas_energy_gj_day"]),
        ("Syngas self-sufficiency (%)", e["self_sufficiency_pct"]), ("CAPEX (USD)", e["capex_usd"]),
        ("Revenue / OPEX / EBITDA (USD/yr)", f"{e['revenue_usd_yr']} / {e['opex_usd_yr']} / {e['ebitda_usd_yr']}"),
        ("After-tax cash flow (USD/yr)", e["after_tax_cashflow_usd_yr"]), ("Payback (yr)", e["payback_yr"]),
        ("5-yr NPV at 14% (USD)", e["npv_usd"]), ("IRR (%)", e["irr_pct"]),
        ("CO2e avoided (t/yr)", e["co2e_avoided_t_yr"])])
    files = collect()
    tree = "\n".join(f"  {rel}" for rel, _ in files)
    parts = [HEADER.replace("@@KPI@@", kpi), "\n## File tree\n" + tree + "\n\n## Files\n"]
    for rel, text in files:
        lang = LANG.get(Path(rel).suffix, "text")
        parts.append(f'\n<file path="{rel}" language="{lang}">\n{text.rstrip()}\n</file>\n')
    out = DIST / "waste-tyre-pyrolysis-simulator_bundle.md"
    out.write_text("".join(parts), encoding="utf-8")
    return out, len(files)


def build_single_html():
    web = ROOT / "web"
    html = (web / "index.html").read_text(encoding="utf-8")
    css = (web / "style.css").read_text(encoding="utf-8")
    js = (web / "app.js").read_text(encoding="utf-8")
    base = (ROOT / "data" / "baseline_10tpd_nairobi.json").read_text(encoding="utf-8")
    fetch_call = "fetch('baseline_10tpd_nairobi.json').then(r => r.json())"
    for needle in ('<link rel="stylesheet" href="style.css">', '<script src="app.js" defer></script>', "</body>", fetch_call):
        assert needle in (html + js), f"build anchor missing: {needle}"
    js = js.replace(fetch_call, "Promise.resolve(window.__BASELINE__)")
    html = html.replace('<link rel="stylesheet" href="style.css">', f"<style>\n{css}\n</style>")
    html = html.replace('<script src="app.js" defer></script>\n', "")
    html = html.replace("</body>", f"<script>window.__BASELINE__ = {base};</script>\n<script>\n{js}\n</script>\n</body>")
    out = DIST / "waste-tyre-pyrolysis-simulator.html"
    out.write_text(html, encoding="utf-8")
    return out


if __name__ == "__main__":
    DIST.mkdir(exist_ok=True)
    b, n = build_bundle()
    h = build_single_html()
    print(f"{b.name}: {n} files, {b.stat().st_size // 1024} KB\n{h.name}: {h.stat().st_size // 1024} KB")
